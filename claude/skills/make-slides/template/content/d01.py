from deck import arrow, box, hbars, say, src, svg, table, terms, txt


def build(D):
    D.set_goals("인덱스 없이 찾을 때 무엇이 느린지 말할 수 있다",
                "B-tree 가 몇 번 만에 행을 찾는지 계산할 수 있다")
    D.section("왜 필요한가")
    D.slide("인덱스가 없으면 행 하나를 찾으려고 표 전체를 읽는다",
            hbars([("전체 훑기", 1_000_000, "bad"), ("B-tree 인덱스", 20, "ok")], unit="행", label="찾을 때 읽는 행 수"),
            say("행이 100만 개면 전체 훑기는 100만 행을 읽고, B-tree 는 높이만큼인 약 20번만 내려갑니다."),
            src("행 100만 개, 한 노드에 2갈래로 단순화한 계산(log2 1,000,000 ≈ 20)"))
    D.section("어떻게 하나")
    D.slide("B-tree 는 정렬된 사본을 위에서부터 갈래를 골라 내려간다",
            svg(1100, 230,
                box(450, 10, 200, 56, "뿌리", "1-500 | 501-1000", "acc"),
                box(180, 140, 200, 56, "1-500", "1-250 | 251-500"),
                box(720, 140, 200, 56, "501-1000", "501-750 | 751-1000", "mute"),
                arrow(520, 66, 300, 138, cls="acc"), arrow(580, 66, 800, 138),
                txt(30, 222, "찾는 값 300: 뿌리에서 왼쪽, 다음 층에서 251-500 갈래", "sm"),
                label="B-tree 두 층"),
            terms([("B-tree", "키를 정렬해 여러 갈래 노드에 나눠 둔 트리", "전화번호부의 ㄱ·ㄴ·ㄷ 탭")]))
    D.summary([("인덱스가 없으면", "행 하나를 찾아도 전체를 읽는다"),
               ("B-tree", "높이만큼만 내려가 찾는다(100만 행에 약 20번)")])
    D.quiz([("행이 100만 개인 표에서 B-tree(2갈래 단순화)는 몇 번 내려가나?", "약 20번",
             "log2 1,000,000 ≈ 20. 실제 DB 는 노드 한 장에 수백 갈래라 3-4번입니다.")])
